C IRONS, B.M., "A FRONTAL SOLUTION PROGRAM FOR FINITE ELEMENT
C ANALYSIS", INT. J. NUMER. METH. ENGNG, 2, 5-32 (1970).
C APPENDIX II: SUBROUTINE CODEST AND MASTER ZIPP (PP 22-29).
C
C TRANSCRIBED FROM THE PRINTED LISTING. THE ALGORITHM, STATEMENT
C ORDER, LABELS AND VARIABLE NAMES ARE AS PRINTED. THE ONLY
C CHANGES ARE TRANSLATIONS OF ICT 1905 FORTRAN AND HOOKS FOR THE
C TEST PROGRAMS, EACH MARKED "*** CHANGED" OR "*** ADDED":
C
C 1. DOUBLE PRECISION (IMPLICIT REAL*8). THE LISTING EQUIVALENCES
C    INTEGER NIX(6000) WITH ELPA(3000) AND SETS NIXEND = 5400 FOR
C    "A COMPUTER THAT USES TWO INTEGER WORDS FOR A FLOATING-POINT
C    NUMBER" (APPENDIX I). AN 8-BYTE REAL AND 4-BYTE INTEGERS GIVE
C    EXACTLY THAT LAYOUT. (THE ICT 1905 WORD WAS 24 BITS, ITS REAL
C    48 BITS, ABOUT 11 DIGITS.)
C 2. ICT MULTIPLE ASSIGNMENT, E.G. "NIC, LDES = NIX(NEW)", IS
C    WRITTEN AS SEPARATE ASSIGNMENTS OF THE SAME VALUE.
C 3. FORMAT(40I0) / (2I0,40F0.0) WERE ICT FREE-FORMAT CARD READS;
C    THEY ARE LIST-DIRECTED READS HERE. HOLLERITH TEXT IN FORMATS
C    IS WRITTEN AS QUOTED STRINGS (SAME TEXT).
C 4. MASTER ZIPP IS A SUBROUTINE, AND STOP AT 140 IS A RETURN, SO
C    A TEST PROGRAM CAN CALL IT. CARD READER 5, PRINTER 6 AND TAPES
C    1 AND 2 ARE THE UNITS NCARD, NPRT, NTP1, NTP2 IN /ZIPIO/.
C 5. IBA IS GIVEN A VALUE (NBAXO) BEFORE THE FIRST ELEMENT IS READ.
C    THE LISTING WRITES "IBA, (ELPA(I), I = NBAXO,IBA)" FOR THE
C    FIRST ELEMENT WITH IBA NOT YET SET. THE PAPER'S TAPE EXAMPLE
C    SHOWS THIS RECORD AS A NULL BLOCK, "ELPA(NBAXO) ONLY".
C 6. CALLS TO A USER ROUTINE FRNOUT REPORT ANSWERS, PIVOT CRITERIA
C    AND ERRORS TO THE TEST PROGRAM. THEY DO NOT AFFECT THE SOLUTION.
C
C=======================================================================
C
C     FRONT SOLUTION, MARK V, WRITTEN BY B. IRONS, UNIVERSITY COLLEGE,
C     SWANSEA.
C
C
C=======================================================================
C
      SUBROUTINE CODEST
C
C     (INTERPRETS CODED ELEMENT DESTINATIONS FROM LDEST.)
C
C *** CHANGED: IMPLICIT REAL*8 (SEE NOTE 1)
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON ELPA(3000), LVABL(30), LDEST(30), MVABL(60), ELCOR(3,20),
     1   INITL, NTIREX, NEWRHS, NELEM, NELEMZ, KUREL, LPREQ,
     2   LZ, NELZ, NBAXO, NBZ, KL, LDES, NSTRES
      LDES = LDEST(KL)
C     LDES BECOMES TRUE DESTINATION.
C     NSTRES = N FOR THE FIRST OF N APPEARANCES.
C            = 0 FOR LAST APPEARANCE - BUT SEE BELOW.
C            = -1 FOR INTERMEDIATE APPEARANCES.
C            = 1 FOR ONLY APPEARANCE - I.E. FIRST AND LAST.
      DO 2 NSTRES = 1,1000000
      IF(LDES.LT.1000) GO TO 4
      LDES = LDES - 1000
    2 CONTINUE
    4 NSTRES = NSTRES - 2
      RETURN
      END
C
C=======================================================================
C
C *** CHANGED: "MASTER ZIPP" IS A SUBROUTINE (NOTE 4)
      SUBROUTINE ZIPP
C
C     (PRE-FRONT AND FRONT ROUTINES COMBINED.)
C
C *** CHANGED: IMPLICIT REAL*8 (NOTE 1)
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION NIX(6000), COORD(3,100)
      COMMON ELPA(3000), LVABL(30), LDEST(30), MVABL(60), ELCOR(3,20),
     1   INITL, NTIREX, NEWRHS, NELEM, NELEMZ, KUREL, LPREQ,
     2   LZ, NELZ, NBAXO, NBZ, KL, LDES, NSTRES
C *** ADDED: I/O UNITS (NOTE 4)
      COMMON /ZIPIO/ NCARD, NPRT, NTP1, NTP2
      EQUIVALENCE (NIX(1),ELPA(1)), (COORD(1,1),ELPA(2701))
C
C     THIS FORMULA GIVES THE POSITION IN THE VECTOR OF TERM I,J IN AN
C     UPPER TRIANGULAR MATRIX: I .LE. J.
      NFUNC(I,J) = I + (J*(J-1))/2
C
C     THESE QUANTITIES MUST BE ALTERED WHEN THE DIMENSION STATEMENT
C     IS ALTERED.
      NELPAZ = 3000
      LVEND = 30
      MVEND = 60
      NIXEND = 5400
    2 INITL = 1
C-----CARD INPUT
C     NEWRHS, NTIREX, NRMAX, MAXTAP, MAXELT AS DISCUSSED IN TEXT.
C *** CHANGED: READ(5,900) -> LIST-DIRECTED (NOTES 3,4)
      READ(NCARD,*) NEWRHS, NTIREX, NRMAX, MAXTAP, MAXELT
C     THIS MUST NOT EXCEED NRMAX.
      WRITE(NPRT,802) NEWRHS
  802 FORMAT('1NEW PROBLEM, INITIALLY',I4,3X,'RHS'//)
      WRITE(NPRT,804) NTIREX, NRMAX, MAXTAP, MAXELT
  804 FORMAT(' NTIREX =',I2,4X,'NRMAX =',I2,4X,
     1   'MAXTAP =',I4,4X,'MAXELT =',I4/)
C     THE FIRST OF FIFTEEN ERROR TRAPS.
      JWHERE = 1
      IF(NELPAZ.LE.0. OR .LVEND.LE.0. OR .MVEND.LE.0. OR .NIXEND.LE.0.
     1   OR .NEWRHS.LE.0. OR .NRMAX.LE.0. OR .MAXTAP.LE.0.
     2   OR .MAXELT.LE.0. OR .(NTIREX.NE.0. AND .NTIREX.NE.1)) GO TO 130
C *** CHANGED: "LVMAX, NIZZ, MAXNIC, MAXPA, NVABZ, LCUREQ = 0" (NOTE 2)
      LVMAX = 0
      NIZZ = 0
      MAXNIC = 0
      MAXPA = 0
      NVABZ = 0
      LCUREQ = 0
C     MVABL WILL BE THE VECTOR OF GRANDPA'S NICKNAMES.
      DO 4 I = 1,MVEND
      MVABL(I) = 0
    4 CONTINUE
C
C     PUT ALL ELEMENT NICKNAMES IN LONG VECTOR, NIX.
C
C     NELEM IS ELEMENT NUMBER, KUREL IS CURRENT ELEMENT SIZE. LVABL IS
C     THE LIST OF CURRENT ELEMENT NICKNAMES. ZERO KUREL IS THE NORMAL
C     END TO THE READING OPERATION.
      DO 10 NELEM = 1,1000000
C-----CARD INPUT
C *** CHANGED: READ(5,900) -> LIST-DIRECTED (NOTES 3,4)
      READ(NCARD,*) KUREL, (LVABL(I), I = 1,KUREL)
      JWHERE = 2
C     ERROR TRAP: NEGATIVE KUREL CANNOT BE INTENDED.
      IF(KUREL.LT.0) GO TO 130
      IF(KUREL.EQ.0) GO TO 12
C     LVMAX GIVES SIZE OF LARGEST ELEMENT MATRIX.
      IF(KUREL.LE.LVMAX) GO TO 6
      LVMAX = KUREL
      JWHERE = 3
C     DIMENSIONS OF LVABL, LDEST MUST BE INCREASED.
      IF(LVMAX.GT.LVEND) GO TO 130
C     THIS CHECK IS PRESUMABLY IN ELEMENT ROUTINE.
    6 JWHERE = 4
C     (CHECK COORDINATES AGAINST NEGATIVE AREAS, REFLEX ANGLES ETC.)
C     IS NIX LARGE ENOUGH TO CONTAIN NEXT ELEMENT?
      JWHERE = 5
      IF(NIZZ+KUREL+NELEM.GT.NIXEND) GO TO 130
C     NIZZ BECOMES THE SUM OF ALL THE ELEMENT DEGREES OF FREEDOM.
      DO 8 I = 1,KUREL
      NIC = LVABL(I)
C     NICKNAMES MUST BE POSITIVE INTEGERS.
      JWHERE = 6
      IF(NIC.LE.0) GO TO 130
      NIZZ = NIZZ + 1
C     THE NICKNAMES ARE NOW MADE NEGATIVE TO DISTINGUISH THEM LATER
C     FROM DESTINATIONS.
      NIX(NIZZ) = -NIC
C     THE PROGRAM GIVES A WARNING MESSAGE IF AN ELEMENT CONTAINS A
C     REPEATED NICKNAME.
C     (PRINTED "J = I" OR "J = 1" - THE TYPEFACE DOES NOT DISTINGUISH
C     THEM. J = 1 WOULD COMPARE EACH NICKNAME WITH ITSELF AND WARN FOR
C     EVERY ELEMENT, SO J = I IS THE READING USED.)
      J = I
    7 J = J + 1
      IF(J.GT.KUREL) GO TO 8
      IF(LVABL(J).EQ.NIC) WRITE(NPRT,834) JWHERE, NIC
      GO TO 7
    8 CONTINUE
C     RECORD ELEMENT DIVISIONS, ALSO IN NIX.
      NIX(NIXEND+1-NELEM) = NIZZ
   10 CONTINUE
C     NELEMZ IS THE TOTAL NUMBER OF ELEMENTS.
   12 NELEMZ = NELEM - 1
      N1 = 1
C     NVABZ BECOMES TOTAL NUMBER OF VARIABLES ELIMINATED: LCUREQ
C     BECOMES NUMBER BEFORE CURRENT ELEMENT, LPREQ BEFORE PREVIOUS
C     ELEMENT.
      DO 26 NELEM = 1,NELEMZ
      LPREQ = LCUREQ
      LCUREQ = NVABZ
      NZ = NIX(NIXEND+1-NELEM)
C     WE MUST RECONSTRUCT KUREL (CURRENT ELEMENT SIZE)
      KUREL = NZ - N1 + 1
C
C     FIND NEW NICKNAMES AND USE EXISTING DESTINATIONS.
C
      DO 22 NEW = N1,NZ
C     THIS MAY BE EITHER NICKNAME OR DESTINATION. (A MULTIPLE
C     ASSIGNMENT - NIC, LDES TAKE SAME VALUE)
C *** CHANGED: "NIC, LDES = NIX(NEW)" (NOTE 2)
      NIC = NIX(NEW)
      LDES = NIC
      IF(NIC.GT.0) GO TO 20
C     THUS MAXNIC BECOMES THE LARGEST NICKNAME.
      IF(MAXNIC+NIC.LT.0) MAXNIC = -NIC
C     SEEK LDES I.E. THE DESTINATION BY LOOKING FOR A FREE SPACE IN
C     GRANDPA. IF IT REACHES CONTINUE A NEW SPACE IS NEEDED, AND
C     AUTOMATICALLY LDES BECOMES MAXPA + 1. WE NOW PUT NEW NICKNAME
C     INTO GRANDPA.
      DO 14 LDES = 1,MAXPA
      IF(MVABL(LDES).EQ.0) GO TO 16
   14 CONTINUE
   16 MVABL(LDES) = NIC
      IF(LDES.GT.MAXPA) MAXPA = LDES
C     INCREASE DIMENSION OF MVABL.
      JWHERE = 7
      IF(MAXPA.GT.MVEND) GO TO 130
C     COUNTS 1000 FOR EACH APPEARANCE PLUS ONE.
      KOUNT = 1000
C
C     RECORD FIRST, LAST AND INTERMEDIATE APPEARANCES.
C
C     THIS LOOP COULD PROFITABLY BE WRITTEN IN MACHINE CODE.
      DO 18 LAS = NEW,NIZZ
      IF(NIX(LAS).NE.NIC) GO TO 18
C     REPLACE NICKNAME BY POSITIVE DESTINATION.
      NIX(LAS) = LDES
      KOUNT = KOUNT + 1000
C     BECOMES POSITION OF LAST APPEARANCE IN NIX.
      LAST = LAS
   18 CONTINUE
C     THIS LABELS THE LAST APPEARANCE.
      NIX(LAST) = LDES + 1000
C     THIS LABELS THE FIRST APPEARANCE.
C *** CHANGED: "LDES, NIX(NEW) = LDES + KOUNT" (NOTE 2)
      LDES = LDES + KOUNT
      NIX(NEW) = LDES
C     THIS PROVIDES THE PERMANENT RECORD.
   20 LDEST(NEW-N1+1) = LDES
   22 CONTINUE
C     HERE N1 BECOMES THE PREVIOUS NZ PLUS 1.
      N1 = NEW
C
C     RECONSTRUCT ELEMENT NICKNAMES AND COUPLE WITH DESTINATION VECTORS,
C
C     AND INITIAL ELEMENT STIFFNESS AND LOAD DATA.
C
C     SUBROUTINE CODEST INTERPRETS THE CODED DESTINATIONS.
      DO 24 KL = 1,KUREL
      CALL CODEST
C     HERE WE MUST RECONSTRUCT LVABL.
C *** CHANGED: "NIC, LVABL(KL) = -MVABL(LDES)" (NOTE 2)
      NIC = -MVABL(LDES)
      LVABL(KL) = NIC
C     (COLLECT ELEMENT COORDINATES IN ELCOR, USING VALUE OF NIC)
      IF(NSTRES.NE.0. AND .NSTRES.NE.1) GO TO 24
C     THIS IS NOW THE LAST APPEARANCE OF NIC, SO WE ERASE THE NICKNAME
C     FROM GRANDPA. NVABZ COUNTS THE VARIABLES.
      MVABL(LDES) = 0
      NVABZ = NVABZ + 1
   24 CONTINUE
C-----CARD INPUT, TAPE
C     NOW COMPLETE ELEMENT TAPE BY COMPUTING ELEMENT STIFFNESSES AND
C     LOADS. (FOR RE-SOLUTION WE CREATE ELEMENT DATA DURING
C     BACK-SUBSTITUTION.) REWIND TO USE TAPE.
      CALL ELMAK
   26 CONTINUE
      REWIND NTP1
C
C     PRE-PROGRAM ENDED AND ELEMENT TAPE WRITTEN.
C
C     ESTABLISH STORAGE REQUIREMENTS AND AREA BOUNDARIES.
C
C     HAVE WE EXCEEDED NRMAX RIGHT-HAND-SIDES?
   34 JWHERE = 8
C     CURRENT NUMBER OF RIGHT-HAND-SIDES.
      NRHS = NEWRHS
      IF(NRHS.GT.NRMAX) GO TO 130
C     THERE IS NO LEFT-HAND-SIDE IN RE-SOLUTION.
      IF(INITL.EQ.0) WRITE(NPRT,806) NRHS
  806 FORMAT('1RE-SOLVE WITH',I4,3X,'RHS'//)
C     END OF ELEMENT RECORD IN ELPA.
      NELZ = NFUNC(0,LVMAX+1)*INITL + LVMAX*NRHS
      IF(NELZ.GT.MAXELT) NELZ = MAXELT
C     LOCATION JUST PRECEDING GRANDPA'S RHS.
      NPAR = NFUNC(0,MAXPA+1)*INITL + NELZ
      IF(INITL.EQ.0) GO TO 36
C     END OF GRANDPA FIXES START OF BUFFER AREA FOR EQUATIONS. THIS IS
C     INVIOLATE, SO WE CONSIDER THE WORST RE-SOLUTION CONDITIONS.
C     (CLEARLY MAXNIC EXCEEDS LVMAX.)
      NPAZ = (LVMAX+MAXPA)*NRMAX
      IF(NTIREX.NE.0) NPAZ = (MAXNIC+MAXPA)*NRMAX
      N = NPAR + MAXPA*(NRHS+1)
      IF(N.GT.NPAZ) NPAZ = N
C     NBAXZERO JUST PRECEDES BUFFER AREA.
      NBAXO = NPAZ + 1
C *** CHANGED: ADDED - IBA SET BEFORE THE FIRST ELEMENT (NOTE 5)
      IBA = NBAXO
C     THE END OF THE EQUATION BUFFER AREA.
      NBAXZ = NBAXO + MAXTAP
      IF(NBAXZ.GT.NELPAZ) NBAXZ = NELPAZ
C     THIS IS THE LENGTH OF BUFFER ACTUALLY AVAILABLE.
      NBUFFA = NBAXZ - NBAXO
C     IS IT ENOUGH? - IF NOT, BUY A LARGER COMPUTER.
      JWHERE = 9
      IF(NBUFFA.LT.MAXPA+NRMAX+3) GO TO 130
C     NRUNZERO JUST PRECEDES THE RUNNING VARIABLES.
      NRUNO = NPAZ - NRMAX*MAXPA
C     WE MUST NOT ZERO BUFFER AREA PRIOR TO THE RE-SOLUTION.
   36 DO 38 I = 1,NBAXO + INITL*NBUFFA
      ELPA(I) = 0.0
   38 CONTINUE
C     BECOMES THE CURRENT SIZE OF GRANDPA.
      KURPA = 0
C
C     SEEK AND ASSEMBLE NEW ELEMENT.
C
C     ASSEMBLE AND REDUCE FOR EACH ELEMENT IN TURN.
      DO 92 NELEM = 1,NELEMZ
C-----TAPE
C     IN RE-SOLUTION, ELEMENTS ARE IN REVERSED ORDER.
      IF(INITL.EQ.0) BACKSPACE NTP1
C     ELEMENT DATA WITH ASSOCIATED EQUATIONS.
      READ(NTP1) KUREL, LPREQ, (LVABL(I), LDEST(I), I = 1,KUREL),
     1   LZ, (ELPA(I), I = 1,LZ)
C     (FOLLOWED BY THE ELEMENT COORDINATES IN THE SAME TAPE RECORD.)
      IF(INITL.EQ.0) BACKSPACE NTP1
C     CREATE TAPE READY FOR BACK-SUBSTITUTION.
      WRITE(NTP2) KUREL, LPREQ, (LVABL(I), LDEST(I), I = 1,KUREL),
     1   IBA, (ELPA(I), I = NBAXO,IBA)
C     (FOLLOWED BY THE ELEMENT COORDINATES IN THE SAME TAPE RECORD.)
C     IS THE ELEMENT STIFFNESS SEGMENT TOO LONG?
      JWHERE = 10
      IF(LZ.GT.NELZ. OR .LZ.LE.0) GO TO 130
      WRITE(NPRT,808) NELEM
  808 FORMAT(/' ELEMENT',I4/)
      WRITE(NPRT,800) (ELPA(I), I = 1,LZ)
      WRITE(NPRT,810) KUREL, LPREQ, (LVABL(I), I = 1,KUREL)
  810 FORMAT(/' KUREL =',I4,4X,'LPREQ =',I4//' NICKNAMES =',(15I7))
C     WRITE(NPRT,812) (LDEST(I), I = 1,KUREL)
C 812 FORMAT(/' DESTINATION VECTOR =',(15I7))
C     IBA BECOMES POSITION IN EQUATION.
C     BECAUSE BUFFER AREA CLEARED FOR NEW ELEMENT.
      IBA = NBAXO
C     TRIGGERS TAPE READ FOR FIRST EQUATION NEEDED.
      NEW = 1
      L = 0
C     FIND DESTINATIONS READY FOR ELEMENT ASSEMBLY, AND STORE THEM
C     TEMPORARILY IN LVABL. WE KEEP NICKNAMES IN MVABL.
      DO 40 KL = 1,KUREL
      CALL CODEST
      MVABL(LDES) = LVABL(KL)
      LVABL(KL) = LDES
C     GRANDPA MAY NEED ENLARGING FOR NEW INTAKE.
      IF(LDES.GT.KURPA) KURPA = LDES
   40 CONTINUE
C     PROCESS LHS AND RHS IN TURN, EXCEPT IN RE-SOLUTION.
      DO 66 LHSRHS = 2-INITL, 2
C     LHS IS 1 FOR LEFT-HAND-SIDE PROCESS.
      LHS = 2 - LHSRHS
C     IRHS IS 1 FOR RIGHT-HAND-SIDE PROCESS.
      IRHS = 1 - LHS
C     TELESCOPE LHS AND RHS ASSEMBLY PROCESSES.
      DO 64 KL = 1, LHS*KUREL+IRHS*NRHS
      GO TO (42,44), LHSRHS
   42 KG = LVABL(KL)
C     A STARTING LOCATION WITHIN GRANDPA.
      MGO = NFUNC(0,KG) + NELZ
      GO TO 46
C     THE SAME FOR RIGHT-HAND-SIDE ASSEMBLY.
   44 MGO = (KL-1)*MAXPA + NPAR
   46 DO 62 IL = 1, LHS*KL+IRHS*KUREL
      IG = LVABL(IL)
C     WILL BECOME POSITION IN ELEMENT SEGMENT IN ELPA.
      L = L + 1
C     THIS IS THE ELEMENT CONTRIBUTION.
   48 CE = ELPA(L)
      GO TO (50,56), LHSRHS
C     LOWER OR UPPER TRIANGLE, OR DIAGONAL TERM? (IF TWO NICKNAMES ARE
C     THE SAME IN THE ELEMENT, THEIR OFF-DIAGONAL CONTRIBUTION TO
C     GRANDPA'S DIAGONAL MUST BE DOUBLED, AS IN THIS STATEMENT.)
   50 IF(KG-IG) 52,54,56
   52 MG = NFUNC(KG,IG) + NELZ
      GO TO 58
   54 IF(KL.NE.IL) CE = CE+CE
   56 MG = MGO + IG
C     DO WE NEED A NEW TAPE RECORD FOR A FRAGMENTED ELEMENT? THIS WOULD
C     ENTAIL AN ELEMENT CONTINUATION RECORD. THE ELEMENTS ARE IN
C     REVERSE ORDER IN THE RE-SOLUTION MODE.
   58 IF(L.LE.LZ) GO TO 60
C-----TAPE
      IF(INITL.EQ.0) BACKSPACE NTP1
      READ(NTP1) LZ, (ELPA(I), I = 1,LZ)
      IF(INITL.EQ.0) BACKSPACE NTP1
      WRITE(NPRT,814)
  814 FORMAT(/' ELEMENT CONTINUATION')
      WRITE(NPRT,800)(ELPA(I), I = 1,LZ)
C     IS THE ELEMENT CONTINUATION SEGMENT LONGER THAN ALLOWED?
      JWHERE = 11
      IF(LZ.GT.NELZ. OR .LZ.LE.0) GO TO 130
C     START AGAIN TO USE THE NEW ELEMENT SEGMENT.
      L = 1
      GO TO 48
C     AT LAST WE ASSEMBLE THE ELEMENT COEFFICIENT.
   60 ELPA(MG) = ELPA(MG) + CE
   62 CONTINUE
   64 CONTINUE
   66 CONTINUE
C     BUT WERE THE CORRECT NUMBER OF TERMS ASSEMBLED?
      JWHERE = 12
      IF(L.NE.LZ) GO TO 130
C     WRITE(NPRT,816)
C 816 FORMAT(/' GRANDPA')
C     WRITE(NPRT,800)(ELPA(I), I = NELZ+1,NPAZ)
C
C     ELIMINATE VARIABLE IN POSITION LDES, AND WRITE EQUATION FOR TAPE.
C
C     LOOK THROUGH CURRENT ELEMENT VARIABLES.
C     - ARE THERE ANY READY FOR ELIMINATION?
      DO 90 KL = 1,KUREL
      CALL CODEST
      IF(NSTRES.NE.0. AND .NSTRES.NE.1) GO TO 90
C     THE END OF THE EQUATION FOR BACK-SUBSTITUTION.
C     - BUT ONLY IF THERE IS ROOM.
   68 NDEQN = IBA + KURPA + NRMAX + 3
      IF(NDEQN.LE.NBAXZ. AND .NEW.EQ.0) GO TO 70
C-----TAPE
      IF(NEW.EQ.0) WRITE(NTP2) IBA, (ELPA(I), I = NBAXO,IBA)
C     START AGAIN IN NEW BLOCK OF EQUATIONS.
      IBA = NBAXO
C     DE-TRIGGER IF SENSITISED FOR TAPE READ.
      NEW = 0
C     WE MUST NOW RE-CALCULATE NDEQN.
      IF(INITL.NE.0) GO TO 68
C-----TAPE
C     IN THE RE-SOLUTION WE MUST READ FRESH EQUATIONS WHENEVER WE WRITE
C     THE CURRENT BLOCK ON TAPE.
      BACKSPACE NTP1
      READ(NTP1) NBZ, (ELPA(I), I = NBAXO,NBZ)
      BACKSPACE NTP1
C     WRITE(NPRT,818)(ELPA(I), I = NBAXO,NBZ)
C 818 FORMAT(/' RAW EQUATIONS ARE'/(12F10.5))
      GO TO 68
C     IBDIAG WILL BE THE POSITION OF THE DIAGONAL TERM IN THE EQUATION,
C     AND NDIAG THE POSITION IN GRANDPA. WE NEED NDIAG IN THE FIRST
C     SOLUTION, IBDIAG IN THE RE-SOLUTION.
C *** CHANGED: "IBDIAG, NDIAG = IBA + LDES" (NOTE 2)
   70 IBDIAG = IBA + LDES
      NDIAG = IBDIAG
      IF(INITL.NE.0) NDIAG = NFUNC(0,LDES+1) + NELZ
      PIVOT = ELPA(NDIAG)
      ELPA(NDIAG) = 0.0
C     A PERFECT "FLYING STRUCTURE" (UNEARTHED) IS RARE, BUT WE TEST FOR
C     THIS MISTAKE HERE.
      JWHERE = 13
      IF(PIVOT.EQ.0.) GO TO 130
C     WILL BECOME THE END OF THE INNERMOST LOOP.
      MGZ = NELZ
C     LAST COLUMN IN GRANDPA TO BE PROCESSED.
      JGZ = KURPA
C     PRESERVE INITIAL VALUE TO CALCULATE NDELT BELOW.
      IBO = IBA
C     WE ONLY PROCESS RHS IN RE-SOLUTION.
      IF(INITL.EQ.0) IBA = IBA + KURPA
C     PROCESS LHS, THEN PROCESS RHS.
      DO 86 LHSRHS = 2-INITL, 2
      IF(LHSRHS.EQ.2) JGZ = NRHS
      DO 84 JG = 1,JGZ
C     PROCEED ALONG EQUATION.
      IBA = IBA + 1
      GO TO (72,76), LHSRHS
C     THIS WILL DEFINE START OF THE INNERMOST LOOP.
   72 MGO = MGZ
      MGZ = MGO + JG
      IF(LDES.GT.JG) GO TO 74
C     POSITION OF COEFFICIENT IN GRANDPA FOR THE EQUATION FOR
C     BACK-SUBSTITUTION.
      MG = MGO + LDES
      GO TO 78
   74 MG = NFUNC(JG,LDES) + NELZ
      GO TO 78
   76 MGO = (JG-1)*MAXPA + NPAR
      MG = MGO + LDES
      MGZ = MGO + KURPA
C     QUANTITY NEEDED FOR STANDARDISED LOOP.
   78 NDELT = IBO - MGO
C     PUT COEFFICIENT INTO EQUATION.
C *** CHANGED: "CONST, ELPA(IBA) = ELPA(MG)" (NOTE 2)
      CONST = ELPA(MG)
      ELPA(IBA) = CONST
C     DO THIS TO SAVE COMPUTER TIME ONLY.
      IF(CONST.EQ.0.) GO TO 84
C     ANOTHER QUANTITY NEEDED FOR INNERMOST LOOP.
      CONST = CONST/PIVOT
C     LEAVE BEHIND ZERO IN GRANDPA. CALCULATE ROUNDOFF CRITERION, IN
C     FIRST SOLUTION ONLY.
      ELPA(MG) = 0.0
      IF(INITL.NE.LHSRHS) GO TO 80
C
C     SIMULTANEOUSLY, CREATE A SIMPLE ROUNDOFF CRITERION.
C
      MG = NPAR + NRHS*MAXPA + JG
      ELPA(MG) = ELPA(MG) + ELPA(MGZ)**2
C
C     STANDARDISED INNERMOST LOOP, OBVIOUSLY SUITABLE FOR WRITING AS A
C     ROUTINE IN THE BASIC MACHINE CODE.
   80 DO 82 I = MGO+1, MGZ
      ELPA(I) = ELPA(I) - CONST*ELPA(I+NDELT)
   82 CONTINUE
C
   84 CONTINUE
   86 CONTINUE
C     REPLACE DIAGONAL COEFFICIENT THAT WAS MADE ZERO.
      ELPA(IBDIAG) = PIVOT
C     PREPARE FOR THE NEXT EQUATION.
      IBA = NDEQN
C     CURRENT SIZE OF GRANDPA, I.E. EQUATION LENGTH.
      ELPA(IBA) = KURPA
C     DESTINATION GIVES POSITION OF DIAGONAL TERM.
      ELPA(IBA-1) = LDES
C     NICKNAME OF VARIABLE NOW BEING TREATED.
      ELPA(IBA-2) = MVABL(LDES)
C     EXAMINE ROUNDOFF CRITERION, FIRST SOLUTION ONLY.
      IF(INITL.EQ.0) GO TO 88
      MG = NPAR + NRHS*MAXPA + LDES
C     THIS IS THE SIMPLE ROUNDOFF CRITERION.
      CRIT = SQRT(ELPA(MG))/ABS(PIVOT)
C     LEAVE ZERO IN THE LOCATION RESERVED FOR THE NEXT ACCUMULATION,
C     FOR ANOTHER CRITERION.
      ELPA(MG) = 0.0
C *** ADDED: REPORT THE PIVOT AND ITS CRITERION (NOTE 6)
      CALL FRNOUT(5, NRHS, MAXNIC, MAXPA, 0, CRIT, PIVOT,
     1            MVABL(LDES))
C     DISASTER - FLYING STRUCTURE OR MECHANISM.
      JWHERE = 14
      IF(CRIT.GT.1.0E8) GO TO 130
C     POSSIBLE ROUNDOFF TROUBLE: THIS GIVES A WARNING MESSAGE TO HELP
C     IDENTIFY THE CAUSE, BUT WITHOUT STOPPING THE COMPUTER.
      JWHERE = 15
      IF(CRIT.GT.1.0E4. OR .PIVOT.LT.0.)
     1   WRITE(NPRT,834) JWHERE, NIC, CRIT, PIVOT
C     WRITE(NPRT,820)
C 820 FORMAT(/' AFTER ELIMINATION')
C     WRITE(NPRT,816)
C     WRITE(NPRT,800)(ELPA(I), I = NELZ+1, NPAZ)
C     WRITE(NPRT,822)
C 822 FORMAT(/' EQUATIONS')
C     WRITE(NPRT,800)(ELPA(I), I = NDEQN-KURPA-NRMAX-2, NDEQN)
C     DELETE FROM LIST OF GRANDPA'S NICKNAMES.
   88 MVABL(LDES) = 0
C     CAN WE NOW WORK WITH A SMALLER GRANDPA? (NEW ZERO MAY EXPOSE A
C     BLOCK OF FURTHER ZEROS.)
      IF(MVABL(KURPA).NE.0) GO TO 90
      KURPA = KURPA - 1
C     THIS PARTICULAR SAFEGUARD SHOULD NEVER BE NEEDED: EXTRA SAFETY
C     FOR FOOLPROOF PROGRAM.
      IF(KURPA.NE.0) GO TO 88
   90 CONTINUE
   92 CONTINUE
C     ZERO LATEST ELEMENT INPUT, SO THAT FOR ENTIRE OUTPUT ANY NICKNAME
C     NOT USED IS ASSOCIATED WITH ZERO DISPLACEMENTS.
      DO 94 I = 1,NELZ*NTIREX
      ELPA(I) = 0.0
   94 CONTINUE
C
C     BACK-SUBSTITUTE INTO EQUATIONS, TAKEN IN REVERSE ORDER.
C
C-----TAPE
      IF(INITL.NE.0) REWIND NTP1
C     WE ARE ALREADY EFFECTIVELY IN RE-SOLUTION PHASE.
      INITL = 0
C-----CARD INPUT
C     NUMBER OF RIGHT-HAND-SIDES IN NEXT RE-SOLUTION.
C *** CHANGED: READ(5,900) -> LIST-DIRECTED (NOTES 3,4)
      READ(NCARD,*) NEWRHS
      WRITE(NPRT,824) NEWRHS
  824 FORMAT(//' BACK-SUBSTITUTION STARTS, AND NEXT NO. OF',
     1   ' RHS WILL BE',I4/)
C     ACTUAL EFFECTIVE END OF EQUATION BUFFER BLOCK.
      NBZ = IBA
C     THIS WILL COUNT THE EQUATIONS BACKWARDS.
      NEQ = NVABZ
C     WE SET THE FIRST VALUE: LATER VALUES FROM TAPE.
      LPREQ = LCUREQ
C     THE PROGRAM MUST ALSO COUNT ELEMENTS BACKWARDS.
      NELEM = NELEMZ
C     DO WE NEED ANOTHER BLOCK OF EQUATIONS YET?
  100 IF(IBA.NE.NBAXO) GO TO 102
C-----TAPE
      BACKSPACE NTP2
      READ(NTP2) NBZ, (ELPA(I), I = NBAXO,NBZ)
      BACKSPACE NTP2
C     WE START AT THE END OF THE LAST EQUATION.
      IBA = NBZ
C     THIS GIVES US THE LENGTH OF THE EQUATION.
  102 KURPA = ELPA(IBA)
C     THIS GIVES THE POSITION OF THE DIAGONAL TERM.
      LDES = ELPA(IBA-1)
C     THIS GIVES THE NICKNAME OF THE CURRENT VARIABLE.
      NIC = ELPA(IBA-2)
C     FIND WHERE THE RHS OF THE EQUATION STARTS.
      IBAR = IBA - NRMAX - 3
C     POSITION PRECEDING THE START OF THE EQUATION.
      IBA = IBAR - KURPA
C     POSITION IN ELPA OF THE DIAGONAL COEFFICIENT.
      IBDIAG = IBA + LDES
C     THIS WAS THE PIVOT IN THE REDUCTION PROCESS.
      PIVOT = ELPA(IBDIAG)
C     WRITE(NPRT,822)
C     WRITE(NPRT,800)(ELPA(I), I = IBA+1,NBZ)
C     SET THE DIAGONAL ZERO TO SIMPLIFY THE CODING.
      ELPA(IBDIAG) = 0.0
C     DEAL WITH EACH RIGHT-HAND-SIDE IN TURN.
      DO 106 J = 1,NRHS
C     MGZERO IS THE START OF THE RUNNING VARIABLES FOR THE CURRENT
C     RIGHT-HAND-SIDE.
      MGO = NRUNO + (J-1)*MAXPA
      MGZ = MGO + KURPA
C     NEEDED FOR THE STANDARDISED INNERMOST LOOP.
      CONST = ELPA(IBAR+J)
C     ALSO NEEDED.
      NDELT = IBA - MGO
C
C     INNERMOST LOOP, SUITABLE FOR WRITING AS A SPECIAL ROUTINE IN SOME
C     BASIC MACHINE CODE.
      DO 104 I = MGO+1, MGZ
      CONST = CONST - ELPA(I)*ELPA(I+NDELT)
  104 CONTINUE
C
C     PLACE ANSWERS AND PREPARE FOR NEW ITERATIVE LOOP.
C
C     PLACE ANSWERS IN THE RUNNING VARIABLES.
C *** CHANGED: "ANSWER, ELPA(MGO+LDES) = CONST/PIVOT" (NOTE 2)
      ANSWER = CONST/PIVOT
      ELPA(MGO+LDES) = ANSWER
C     ALSO, FOR ENTIRE OUTPUT, IN POSITION NIC.
      IF(NTIREX.NE.0) ELPA(NIC) = ANSWER
      NIC = NIC + MAXNIC
  106 CONTINUE
C     REPLACE DIAGONAL COEFFICIENT WHICH WAS SET TO ZERO. IN LAST
C     RE-SOLUTION NEWRHS IS NEGATIVE AND IT IS THEREFORE NOT WORTHWHILE
C     TO WRITE TAPE.
      ELPA(IBDIAG) = PIVOT
C-----TAPE
      IF(IBA.EQ.NBAXO. AND .NEWRHS.GT.0)
     1   WRITE(NTP1) NBZ, (ELPA(I), I = NBAXO,NBZ)
C     WRITE(NPRT,826)(ELPA(I), I = NBAXO,NBZ)
C 826 FORMAT(/' EQUATIONS AS WRITTEN ON TAPE 1 ARE'/(12F10.5))
C     NUMBER OF VARIABLES YET TO BE CALCULATED.
      NEQ = NEQ - 1
C     OTHERWISE WE SHALL NEED A NEW ELEMENT.
  108 IF(NEQ.NE.LPREQ) GO TO 100
C-----TAPE
      BACKSPACE NTP2
      READ(NTP2) KUREL, LPREQ, (LVABL(I), LDEST(I), I = 1,KUREL),
     1   NBZ, (ELPA(I), I = NBAXO,NBZ)
C     (FOLLOWED BY THE ELEMENT COORDINATES IN THE SAME RECORD.)
      BACKSPACE NTP2
C     START AGAIN AT THE END OF THE LAST EQUATION.
      IBA = NBZ
      IF(NTIREX.NE.0) GO TO 114
C     (NOW PLACE ANSWERS FOR OUTPUT BY ELEMENTS.)
C     IN ORDER TO FIND ELEMENT VARIABLES IN VECTOR OF RUNNING
C     VARIABLES.
      DO 112 KL = 1,KUREL
      CALL CODEST
      NRUN = NRUNO + LDES
C     POSITION IN ELEMENT OUTPUT IN ELPA.
      DO 110 L = KL, NRHS*KUREL, KUREL
      ELPA(L) = ELPA(NRUN)
C     REQUIRED POSITION AMONGST RUNNING VARIABLES.
      NRUN = NRUN + MAXPA
  110 CONTINUE
  112 CONTINUE
      WRITE(NPRT,828) NELEM
  828 FORMAT(/' ANSWERS, ELEMENT',I4/)
      WRITE(NPRT,810) KUREL, LPREQ, (LVABL(I), I = 1,KUREL)
      WRITE(NPRT,800)(ELPA(I), I = 1,KUREL*NRHS)
C *** ADDED: HAND THE ELEMENT ANSWERS TO THE TEST PROGRAM (NOTE 6)
      CALL FRNOUT(1, NRHS, MAXNIC, MAXPA, 0, 0.0D0, 0.0D0, 0)
C-----CARD INPUT, TAPE
  114 CALL ELMAK
C     LOOK AGAIN THROUGH THE ELEMENT VARIABLES: IS IT THE LAST
C     APPEARANCE OF THE NODE IN THE BACK-SUBSTITUTION, I.E., FIRST IN
C     REDUCTION?
      DO 116 KL = 1,KUREL
      CALL CODEST
      IF(NSTRES.LE.0) GO TO 116
      NIC = LVABL(KL)
C     (FIND AVERAGE OF THE (NSTRES) VALUES OF STRESS AT NODE NIC.)
  116 CONTINUE
C     PASS ON TO THE NEXT ELEMENT - IF THERE IS ONE.
      NELEM = NELEM - 1
      IF(NELEM.NE.0) GO TO 108
      IF(NTIREX.NE.0) WRITE(NPRT,830)(ELPA(I), I = 1,MAXNIC*NRHS)
  830 FORMAT(/' ENTIRE OUTPUT IS'/(7F17.9))
C *** ADDED: HAND THE ENTIRE OUTPUT TO THE TEST PROGRAM (NOTE 6)
      IF(NTIREX.NE.0)
     1   CALL FRNOUT(2, NRHS, MAXNIC, MAXPA, 0, 0.0D0, 0.0D0, 0)
C     NEW PROBLEM, FINISH, OR RE-SOLUTION RESPECTIVELY
      IF(NEWRHS) 2,140,34
C
C     ERROR DIAGNOSTICS AND FINISH.
C
  130 WRITE(NPRT,832)
  832 FORMAT(/' ERROR')
      WRITE(NPRT,834) JWHERE, NIC, CRIT, PIVOT, LZ, NELZ, NELEM, NRHS,
     1   NBUFFA, LVMAX, NIZZ, NELPAZ, LVEND, MVEND, NIXEND
C *** ADDED: REPORT THE ERROR TO THE TEST PROGRAM (NOTE 6)
      CALL FRNOUT(3, NRHS, MAXNIC, MAXPA, JWHERE, CRIT, PIVOT, NIC)
C     AN ARTIFICE TO PRODUCE TRACE, ETC., FOR AN ERROR DETECTED BY THE
C     PROGRAM. (WITH IEEE ARITHMETIC THIS GIVES INFINITY, NOT A TRAP.)
      A = 0.0
      A = 1.0/A
C *** CHANGED: STOP -> RETURN (NOTE 4)
  140 RETURN
  800 FORMAT(5X,12F9.5)
  834 FORMAT(/' JWHERE =',I3,5X,'NIC =',I4,5X,'CRIT =',E9.2,3X,
     1   'PIVOT =',E12.4,3X,'LZ =',I5,11X,'NELZ =',I5/
     2   ' NELEM =',I4,5X,'NRHS =',I3,5X,'NBUFFA =',I6,4X,
     3   'LVMAX =',I5,10X,'NIZZ =',I5,9X,'NELPAZ =',I5/
     4   ' LVEND =',I4,5X,'MVEND =',I4,3X,'NIXEND =',I6)
      END
