C=======================================================================
C     IRONS (1970) APPENDIX II: SUBROUTINE ELMAK TO DEMONSTRATE THE
C     PROGRAM WITH CARD INPUT (P 29). AS PRINTED, EXCEPT:
C *** CHANGED: IMPLICIT REAL*8; LIST-DIRECTED READ FOR THE ICT FREE-
C *** FORMAT FORMAT(2I0,40F0.0); UNITS 5 AND 1 ARE NCARD AND NTP1.
C=======================================================================
      SUBROUTINE ELMAK
C
      IMPLICIT REAL*8 (A-H,O-Z)
      DIMENSION EL(100)
      COMMON ELPA(3000), LVABL(30), LDEST(30), MVABL(60), ELCOR(3,20),
     1   INITL, NTIREX, NEWRHS, NELEM, NELEMZ, KUREL, LPREQ,
     2   LZ, NELZ, NBAXO, NBZ, KL, LDES, NSTRES
      COMMON /ZIPIO/ NCARD, NPRT, NTP1, NTP2
C
C     IN THIS SECTION CALCULATE ELEMENT STRESSES.
C
      IF(NEWRHS.LE.0) RETURN
C     WRITE(6,802)
C802  FORMAT(/' ELEMENT SEGMENTS AS ORIGINALLY ON TAPE 1')
C
C     NOW CALCULATE ELEMENT RESIDUALS.
C
C-----CARD INPUT
    4 READ(NCARD,*) NGUIDE, LZ, (EL(I), I = 1,LZ)
C     WRITE(6,804) NGUIDE, LZ, (EL(I), I = 1,LZ)
C804  FORMAT(/' NGUIDE =',I2,4X,'LZ =',I4,4X,'EL IS'//(5X,12F9.5))
      NGUID = IABS(NGUIDE)
      GO TO (1,2), NGUID
C-----TAPE
    1 WRITE(NTP1) KUREL, LPREQ, (LVABL(I), LDEST(I), I = 1,KUREL),
     1   LZ, (EL(I), I = 1,LZ)
C     (FOLLOWED BY THE ELEMENT COORDINATES IN THE SAME TAPE RECORD.)
      GO TO 3
C-----TAPE
    2 WRITE(NTP1) LZ, (EL(I), I = 1,LZ)
    3 IF(NGUIDE.GT.0) GO TO 4
      RETURN
      END
